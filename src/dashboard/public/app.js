let sessions = [];
let activeSessionId = null;

function loadSessions() {
  try {
    sessions = JSON.parse(localStorage.getItem('vc_sessions') || '[]');
    activeSessionId = localStorage.getItem('vc_active') || null;
  } catch(e) { sessions = []; }
  if (sessions.length === 0) createSession();
  else if (!sessions.find(s => s.id === activeSessionId)) activeSessionId = sessions[0].id;
}

function saveSessions() {
  localStorage.setItem('vc_sessions', JSON.stringify(sessions));
  localStorage.setItem('vc_active', activeSessionId || '');
}

function createSession(name) {
  const id = 'sess_' + Date.now();
  const s = { id, name: name || 'New Chat', messages: [], createdAt: new Date().toISOString() };
  sessions.unshift(s);
  activeSessionId = id;
  saveSessions();
  renderSessionsList();
  return s;
}

function getActiveSession() {
  return sessions.find(s => s.id === activeSessionId) || sessions[0];
}

function switchSession(id) {
  activeSessionId = id;
  saveSessions();
  renderSessionsList();
  const s = getActiveSession();
  loadSessionIntoChat(s);
}

function deleteSession(id) {
  sessions = sessions.filter(s => s.id !== id);
  if (activeSessionId === id) activeSessionId = sessions[0]?.id || null;
  if (sessions.length === 0) createSession();
  else { saveSessions(); renderSessionsList(); const s = getActiveSession(); loadSessionIntoChat(s); }
}

function loadSessionIntoChat(sess) {
  const container = document.getElementById('chat-messages');
  if (!container) return;
  container.innerHTML = '';
  if (!sess || !sess.messages || sess.messages.length === 0) {
    showWelcome(); return;
  }
  sess.messages.forEach(m => {
    renderMessage(m.role, m.content, m.model, m.tokens, false);
  });
  container.scrollTop = container.scrollHeight;
}

