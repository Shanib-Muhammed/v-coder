function renderMessage(role, content, model, tokens, scroll) {
  const container = document.getElementById('chat-messages');
  if (!container) return;

  // Remove welcome if present
  const wel = container.querySelector('.welcome-message');
  if (wel) wel.remove();

  const isUser = role === 'user';
  const isErr  = role === 'error';

  const formatted = (content || '')
    .replace(/```(\w*)\n([\s\S]*?)```/g, (_, lang, code) =>
      `<pre><code>${escHtml(code.trim())}</code></pre>`)
    .replace(/`([^`]+)`/g, (_, c) => `<code>${escHtml(c)}</code>`)
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/\n/g, '<br>');

  const div = document.createElement('div');
  div.className = 'chat-message ' + (isUser ? 'user' : 'assistant');

  const avatarLetter = isUser ? 'You' : 'VC';
  const modelInfo = model ? model.split('/').pop().slice(0,24) : 'V-Coder';
  const metaText  = isUser ? '' : `<div class="msg-meta">${escHtml(modelInfo)}</div>`;
  const nameText  = isUser ? 'You' : 'V-Coder';
  const errStyle  = isErr ? 'border-color:#DC143C40;' : '';

  div.innerHTML = `
    <div class="msg-avatar">${isUser ? 'U' : 'V'}</div>
    <div class="msg-content">
      <div class="msg-name">${nameText}</div>
      <div class="msg-text" style="${errStyle}">${formatted}</div>
      ${metaText}
    </div>`;

  container.appendChild(div);
  if (scroll !== false) container.scrollTop = container.scrollHeight;
}

