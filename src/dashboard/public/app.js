function initWebSocket() {
  const protocol = location.protocol === 'https:' ? 'wss:' : 'ws:';
  ws = new WebSocket(`${protocol}//${location.host}`);
  ws.onopen  = () => { document.querySelector('.status-dot').style.background = '#22C55E'; };
  ws.onclose = () => { document.querySelector('.status-dot').style.background = '#DC143C'; setTimeout(initWebSocket, 3000); };
  ws.onerror = () => {};
  ws.onmessage = ({ data }) => {
    try {
      const msg = JSON.parse(data);
      handleWSMessage(msg);
    } catch(e) {}
  };
}

function handleWSMessage(msg) {
  removeTypingIndicator();
  isTyping = false;
  document.getElementById('send-btn').disabled = false;
  if (msg.type === 'response') {
    const tok = msg.tokens || msg.usage?.total_tokens || msg.usage?.totalTokenCount || 0;
    if (tok > 0) { sessionTokens += tok; updateModelBadge(); }
    addMessage('assistant', msg.content, { model: msg.model, usage: msg.usage, tokens: tok });
  } else if (msg.type === 'clarification') {
    addMessage('assistant', 'I need clarification:\n\n' + (msg.questions||[]).join('\n'));
  } else if (msg.type === 'error') {
    addMessage('error', '[!] ' + msg.message);
  }
}

